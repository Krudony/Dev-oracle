/**
 * Streams mock response chunks to an SSE writer.
 * @param {string} roleId
 * @param {string} goal
 * @param {Function} onChunk - callback(textChunk)
 * @param {Object} [options]
 * @param {number} [options.chunkDelay=15]
 * @param {boolean} [options.simulateError=false]
 */
export async function streamMockRoleResponse(
  roleId,
  goal,
  onChunk,
  {
    chunkDelay = typeof process !== 'undefined' &&
    (process.env.NODE_ENV === 'test' ||
      process.env.FAST_TEST === '1' ||
      process.argv?.some((a) => a.includes('test')))
      ? 0
      : 15,
    simulateError = false,
  } = {}
) {
  if (simulateError) {
    throw new Error(`[จำลองข้อผิดพลาด] เกิดข้อผิดพลาดขณะวิเคราะห์เอกสารในขั้นตอน ${roleId}`);
  }

  const fullText = generateMockRoleResponse(roleId, goal);
  const words = fullText.split(/(\s+|[.,!?:\n])/);

  for (const token of words) {
    if (!token) continue;
    onChunk(token);
    if (chunkDelay > 0) {
      await new Promise((r) => setTimeout(r, chunkDelay));
    }
  }

  return fullText;
}
